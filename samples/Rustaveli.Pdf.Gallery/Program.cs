using Rustaveli.Pdf;

string output = args.Length > 0 ? args[0] : "gallery.pdf";

Document document = Document.Compose(container =>
{
    container.Section(page =>
    {
        page.Trim = PaperSizes.A4;
        page.Margins = Sides.All(40);
        page.DefaultType = TypeStyle.Default.WithTypeface("Arial").WithPointSize(10);

        page.RunningHead().Compose(ComposeHeader);
        page.RunningFoot().Compose(ComposeFooter);

        // A faint diagonal marking behind everything, ignoring the page margins.
        page.Underlay().Centered().Middle().Text(text =>
            text.Run("SAMPLE").PointSize(96).Ink(Palette.GreyLight));

        page.Body().InsetVertical(20).Stack(column =>
        {
            column.SpaceBetween(18);

            column.Add().Compose(ComposeTypography);
            column.Add().Compose(ComposeBoxes);
            column.Add().Compose(ComposeLists);
            column.Add().Compose(ComposeInvoiceTable);
            column.Add().Compose(ComposeDirection);
            column.Add().Compose(ComposeLinks);
        });
    });
});

document.Info.Title = "Rustaveli.Pdf Gallery";
document.Info.Author = "Rustaveli.Pdf";

document.ExportPdf(output);

Console.WriteLine($"Wrote {output}");
return 0;

static void ComposeHeader(IFrame container) =>
    container.StrokeBottom(1).StrokeInk(Palette.GreyLight).InsetBottom(8).Columns(row =>
    {
        row.Share().Text(text => text.Run("Rustaveli.Pdf").PointSize(16).Bold());

        // No AlignRight here: an Auto item is already snug against its content, and aligning inside one would
        // make it claim the whole row, leaving the relative item beside it with no width at all.
        row.Natural().Text(text => text.Run("Feature gallery").Ink(Palette.GreyDark));
    });

static void ComposeFooter(IFrame container) =>
    container.InsetTop(8).StrokeTop(1).StrokeInk(Palette.GreyLight).InsetTop(6).Columns(row =>
    {
        row.Share().Text(text =>
            text.Run("Generated by Rustaveli.Pdf").Ink(Palette.Grey).PointSize(8));

        row.Natural().Text(text =>
        {
            text.DefaultType(style => style.WithInk(Palette.Grey).WithPointSize(8));
            text.Run("Page ");
            text.Folio().Bold();
            text.Run(" of ");
            text.PageCount().Bold();
        });
    });

static void ComposeSection(IFrame container, string title, Action<IFrame> body) =>
    container.Stack(column =>
    {
        column.SpaceBetween(6);
        column.Add().Text(text => text.Run(title).PointSize(13).Bold().Ink(Palette.Indigo));
        column.Add().Rule(0.5f, Palette.GreyLight);
        column.Add().Compose(body);
    });

static void ComposeTypography(IFrame container) =>
    ComposeSection(container, "Typography", body => body.Stack(column =>
    {
        column.SpaceBetween(3);

        column.Add().Text(text =>
        {
            text.Run("Styles compose: ");
            text.Run("bold").Bold();
            text.Run(", ");
            text.Run("italic").Italic();
            text.Run(", ");
            text.Run("underlined").Underline();
            text.Run(", ");
            text.Run("struck through").StrikeThrough();
            text.Run(", ");
            text.Run("highlighted").Highlight(Palette.Yellow);
            text.Run(", and coloured").Ink(Palette.Red);
            text.Run(".");
        });

        column.Add().Text(text =>
        {
            text.Run("Chemical formulae such as H");
            text.Run("2").Subscript();
            text.Run("O and exponents such as e");
            text.Run("iπ").Superscript();
            text.Run(" sit on shifted baselines.");
        });

        column.Add().Text(text =>
        {
            text.Run("Long paragraphs wrap at the available width and flow onto the next page when they run "
                + "out of room. The engine measures every line before drawing anything, so a break never "
                + "leaves content half-drawn.");
        });

        column.Add().Text(text =>
        {
            text.Centered();
            text.Run("Centred").Ink(Palette.Teal);
        });

        column.Add().Text(text =>
        {
            text.FlushRight();
            text.Run("Right aligned").Ink(Palette.Teal);
        });
    }));

static void ComposeBoxes(IFrame container) =>
    ComposeSection(container, "Boxes, borders and alignment", body => body.Columns(row =>
    {
        row.Gutter(10);

        row.Share().Stroke(1).StrokeInk(Palette.Grey).Inset(8).Stack(column =>
        {
            column.SpaceBetween(4);
            column.Add().Text("Bordered box");
            column.Add().Fill(Palette.GreyLight).Inset(6).Text("With a filled panel inside");
        });

        row.Share().Height(70).Fill(Palette.Indigo).Inset(8).Centered().Middle()
            .Text(text => text.Run("Centred on both axes").Ink(Ink.White));

        row.Fixed(70).Height(70).Proportion(1f).Placeholder(Palette.GreyLight);
    }));

static void ComposeLists(IFrame container) =>
    ComposeSection(container, "Lists, rounded containers and scaling", body => body.Columns(row =>
    {
        row.Gutter(14);

        row.Share().List(list =>
        {
            list.SpaceBetween(2);
            list.Add().Text("A bulleted item");
            list.Add().Text("Another, long enough that it wraps and the continuation lines stay clear of the marker gutter");
            list.Add().Text("A third");
        });

        row.Share().List(list =>
        {
            list.Numbered();
            list.SpaceBetween(2);
            list.MarkerType(style => style.Bold().WithInk(Palette.Indigo));
            list.Add().Text("Numbered items");
            list.Add().Text("keep counting");
            list.Add().Text("across page breaks");
        });

        row.Share().Stack(column =>
        {
            column.SpaceBetween(6);

            column.Add()
                .Fill(Palette.Amber).RoundCorners(8)
                .Inset(8)
                .Text("Rounded fill");

            column.Add()
                .Stroke(1).StrokeInk(Palette.Teal).RoundCorners(8)
                .Inset(8)
                .Text("Rounded outline");

            column.Add().ShrinkToFit()
                .Text("This sentence is scaled down until it fits the column it was given.");
        });
    }));

static void ComposeInvoiceTable(IFrame container) =>
    ComposeSection(container, "Tables", body => body.Table(table =>
    {
        table.Columns(columns =>
        {
            columns.Fixed(70);
            columns.Share();
            columns.Fixed(50);
            columns.Fixed(70);
        });

        table.HeaderRows(header =>
        {
            foreach (string? heading in new[] { "Code", "Description", "Qty", "Amount" })
            {
                header.Cell()
                    .Fill(Palette.Indigo)
                    .Inset(5)
                    .Text(text => text.Run(heading).Bold().Ink(Ink.White));
            }
        });

        for (int index = 1; index <= 18; index++)
        {
            Ink shade = index % 2 == 0 ? Ink.White : Palette.GreyLight;

            table.Cell().Fill(shade).Inset(5).Text($"SKU-{index:D3}");
            table.Cell().Fill(shade).Inset(5).Text($"Line item number {index}");
            table.Cell().Fill(shade).Inset(5).FlushRight().Text($"{index}");
            table.Cell().Fill(shade).Inset(5).FlushRight().Text($"{index * 12.5m:F2}");
        }

        // A footer band, repeated on every page the table spans.
        table.FooterRows(footer =>
        {
            footer.Cell().SpanColumns(3).Inset(5).FlushRight()
                .Text(text => text.Run("Total").Bold());

            footer.Cell().Inset(5).FlushRight()
                .Text(text => text.Run($"{Enumerable.Range(1, 18).Sum(i => i * 12.5m):F2}").Bold());
        });
    }));

static void ComposeDirection(IFrame container) =>
    ComposeSection(container, "Content direction", body => body.Stack(column =>
    {
        column.SpaceBetween(6);

        column.Add().Columns(row =>
        {
            row.Gutter(6);
            row.Fixed(60).Fill(Palette.Teal).Inset(4)
                .Text(text => text.Run("first").Ink(Ink.White));
            row.Fixed(60).Fill(Palette.Cyan).Inset(4).Text("second");
            row.Share().Text(text =>
                text.Run("left to right").Ink(Palette.Grey));
        });

        column.Add().RightToLeft().Columns(row =>
        {
            row.Gutter(6);
            row.Fixed(60).Fill(Palette.Teal).Inset(4)
                .Text(text => text.Run("first").Ink(Ink.White));
            row.Fixed(60).Fill(Palette.Cyan).Inset(4).Text("second");
            row.Share().Text(text =>
                text.Run("right to left").Ink(Palette.Grey));
        });
    }));

static void ComposeLinks(IFrame container) =>
    ComposeSection(container, "Links and sections", body => body.Stack(column =>
    {
        column.SpaceBetween(4);

        column.Add().Anchor("gallery-end").Text("This paragraph is a named destination.");

        column.Add().Text(text =>
        {
            text.Run("An external ");
            text.Link("hyperlink", "https://example.com").Ink(Palette.Blue).Underline();
            text.Run(" and an internal ");
            text.CrossReference("jump", "gallery-end").Ink(Palette.Blue).Underline();
            text.Run(" to the destination above.");
        });
    }));
