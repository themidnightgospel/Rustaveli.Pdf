using Rustaveli.Pdf;

string output = args.Length > 0 ? args[0] : "gallery.pdf";

Document document = Document.Compose(composition =>
{
    composition.Section(section =>
    {
        section.Trim = PaperSizes.A4;
        section.Margins = Sides.All(40);
        section.DefaultType = TypeStyle.Default.WithTypeface("Arial").WithPointSize(10);

        section.RunningHead().Compose(ComposeHeader);
        section.RunningFoot().Compose(ComposeFooter);

        // A faint diagonal marking behind everything, ignoring the page margins.
        section.Underlay().Centered().Middle().Text(text =>
            text.Run("SAMPLE").PointSize(96).Ink(Palette.GreyLight));

        section.Body().InsetVertical(20).Stack(stack =>
        {
            stack.SpaceBetween(18);

            stack.Add().Compose(ComposeTypography);
            stack.Add().Compose(ComposeBoxes);
            stack.Add().Compose(ComposeLists);
            stack.Add().Compose(ComposeInvoiceTable);
            stack.Add().Compose(ComposeDirection);
            stack.Add().Compose(ComposeLinks);
        });
    });
});

document.Info.Title = "Rustaveli.Pdf Gallery";
document.Info.Author = "Rustaveli.Pdf";

document.ExportPdf(output);

Console.WriteLine($"Wrote {output}");
return 0;

static void ComposeHeader(IFrame frame) =>
    frame.StrokeBottom(1).StrokeInk(Palette.GreyLight).InsetBottom(8).Columns(columns =>
    {
        columns.Share().Text(text => text.Run("Rustaveli.Pdf").PointSize(16).Bold());

        // No FlushRight here: a natural column is already snug against its content, and placing inside one would
        // make it claim the whole width, leaving the shared column beside it with none at all.
        columns.Natural().Text(text => text.Run("Feature gallery").Ink(Palette.GreyDark));
    });

static void ComposeFooter(IFrame frame) =>
    frame.InsetTop(8).StrokeTop(1).StrokeInk(Palette.GreyLight).InsetTop(6).Columns(columns =>
    {
        columns.Share().Text(text =>
            text.Run("Generated by Rustaveli.Pdf").Ink(Palette.Grey).PointSize(8));

        columns.Natural().Text(text =>
        {
            text.DefaultType(style => style.WithInk(Palette.Grey).WithPointSize(8));
            text.Run("Page ");
            text.Folio().Bold();
            text.Run(" of ");
            text.PageCount().Bold();
        });
    });

static void ComposeFeature(IFrame frame, string title, Action<IFrame> body) =>
    frame.Stack(stack =>
    {
        stack.SpaceBetween(6);
        stack.Add().Text(text => text.Run(title).PointSize(13).Bold().Ink(Palette.Indigo));
        stack.Add().Rule(0.5f, Palette.GreyLight);
        stack.Add().Compose(body);
    });

static void ComposeTypography(IFrame frame) =>
    ComposeFeature(frame, "Typography", body => body.Stack(stack =>
    {
        stack.SpaceBetween(3);

        stack.Add().Text(text =>
        {
            text.Run("Styles compose: ");
            text.Run("bold").Bold();
            text.Run(", ");
            text.Run("italic").Italic();
            text.Run(", ");
            text.Run("underlined").Underline();
            text.Run(", ");
            text.Run("struck through").StrikeThrough();
            text.Run(", ");
            text.Run("highlighted").Highlight(Palette.Yellow);
            text.Run(", and coloured").Ink(Palette.Red);
            text.Run(".");
        });

        stack.Add().Text(text =>
        {
            text.Run("Chemical formulae such as H");
            text.Run("2").Subscript();
            text.Run("O and exponents such as e");
            text.Run("iπ").Superscript();
            text.Run(" sit on shifted baselines.");
        });

        stack.Add().Text(text =>
        {
            text.Run("Long paragraphs wrap at the available width and flow onto the next page when they run "
                + "out of room. Every line is planned before anything is set, so a new page never "
                + "leaves content half-drawn.");
        });

        stack.Add().Text(text =>
        {
            text.Centered();
            text.Run("Centred").Ink(Palette.Teal);
        });

        stack.Add().Text(text =>
        {
            text.FlushRight();
            text.Run("Right aligned").Ink(Palette.Teal);
        });
    }));

static void ComposeBoxes(IFrame frame) =>
    ComposeFeature(frame, "Frames, strokes and placement", body => body.Columns(columns =>
    {
        columns.Gutter(10);

        columns.Share().Stroke(1).StrokeInk(Palette.Grey).Inset(8).Stack(stack =>
        {
            stack.SpaceBetween(4);
            stack.Add().Text("A stroked frame");
            stack.Add().Fill(Palette.GreyLight).Inset(6).Text("With a filled panel inside");
        });

        columns.Share().Height(70).Fill(Palette.Indigo).Inset(8).Centered().Middle()
            .Text(text => text.Run("Centred on both axes").Ink(Ink.White));

        columns.Fixed(70).Height(70).Proportion(1f).Placeholder(Palette.GreyLight);
    }));

static void ComposeLists(IFrame frame) =>
    ComposeFeature(frame, "Lists, rounded corners and scaling", body => body.Columns(columns =>
    {
        columns.Gutter(14);

        columns.Share().List(list =>
        {
            list.SpaceBetween(2);
            list.Add().Text("A bulleted item");
            list.Add().Text("Another, long enough that it wraps and the continuation lines stay clear of the marker gutter");
            list.Add().Text("A third");
        });

        columns.Share().List(list =>
        {
            list.Numbered();
            list.SpaceBetween(2);
            list.MarkerType(style => style.Bold().WithInk(Palette.Indigo));
            list.Add().Text("Numbered items");
            list.Add().Text("keep counting");
            list.Add().Text("across pages");
        });

        columns.Share().Stack(stack =>
        {
            stack.SpaceBetween(6);

            stack.Add()
                .Fill(Palette.Amber).RoundCorners(8)
                .Inset(8)
                .Text("Rounded fill");

            stack.Add()
                .Stroke(1).StrokeInk(Palette.Teal).RoundCorners(8)
                .Inset(8)
                .Text("Rounded outline");

            stack.Add().ShrinkToFit()
                .Text("This sentence is scaled down until it fits the column it was given.");
        });
    }));

static void ComposeInvoiceTable(IFrame frame) =>
    ComposeFeature(frame, "Tables", body => body.Table(table =>
    {
        table.Columns(columns =>
        {
            columns.Fixed(70);
            columns.Share();
            columns.Fixed(50);
            columns.Fixed(70);
        });

        table.HeaderRows(header =>
        {
            foreach (string heading in new[] { "Code", "Description", "Qty", "Amount" })
            {
                header.Cell()
                    .Fill(Palette.Indigo)
                    .Inset(5)
                    .Text(text => text.Run(heading).Bold().Ink(Ink.White));
            }
        });

        for (int index = 1; index <= 18; index++)
        {
            Ink shade = index % 2 == 0 ? Ink.White : Palette.GreyLight;

            table.Cell().Fill(shade).Inset(5).Text($"SKU-{index:D3}");
            table.Cell().Fill(shade).Inset(5).Text($"Line item number {index}");
            table.Cell().Fill(shade).Inset(5).FlushRight().Text($"{index}");
            table.Cell().Fill(shade).Inset(5).FlushRight().Text($"{index * 12.5m:F2}");
        }

        // Footer rows, repeated on every page the table spans.
        table.FooterRows(footer =>
        {
            footer.Cell().SpanColumns(3).Inset(5).FlushRight()
                .Text(text => text.Run("Total").Bold());

            footer.Cell().Inset(5).FlushRight()
                .Text(text => text.Run($"{Enumerable.Range(1, 18).Sum(i => i * 12.5m):F2}").Bold());
        });
    }));

static void ComposeDirection(IFrame frame) =>
    ComposeFeature(frame, "Reading direction", body => body.Stack(stack =>
    {
        stack.SpaceBetween(6);

        stack.Add().Columns(columns =>
        {
            columns.Gutter(6);
            columns.Fixed(60).Fill(Palette.Teal).Inset(4)
                .Text(text => text.Run("first").Ink(Ink.White));
            columns.Fixed(60).Fill(Palette.Cyan).Inset(4).Text("second");
            columns.Share().Text(text =>
                text.Run("left to right").Ink(Palette.Grey));
        });

        stack.Add().RightToLeft().Columns(columns =>
        {
            columns.Gutter(6);
            columns.Fixed(60).Fill(Palette.Teal).Inset(4)
                .Text(text => text.Run("first").Ink(Ink.White));
            columns.Fixed(60).Fill(Palette.Cyan).Inset(4).Text("second");
            columns.Share().Text(text =>
                text.Run("right to left").Ink(Palette.Grey));
        });
    }));

static void ComposeLinks(IFrame frame) =>
    ComposeFeature(frame, "Links and cross-references", body => body.Stack(stack =>
    {
        stack.SpaceBetween(4);

        stack.Add().Anchor("gallery-end").Text("This paragraph is an anchor.");

        stack.Add().Text(text =>
        {
            text.Run("A ");
            text.Link("link", "https://example.com").Ink(Palette.Blue).Underline();
            text.Run(" to a web page and a ");
            text.CrossReference("cross-reference", "gallery-end").Ink(Palette.Blue).Underline();
            text.Run(" to the anchor above.");
        });
    }));
